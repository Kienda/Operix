import { permissionsForModule, PERMISSIONS } from './permissions';
import { MODULE } from './modules';

/**
 * System role catalog.
 *
 * These roles are seeded into every organization and cannot be deleted, but a
 * Company Owner may clone one into a custom role and adjust it. Role names are
 * never used for authorization decisions — only the permission set is. That is
 * deliberate: `Avoid hard-coded roles` from the product spec.
 */

export const ROLE_SCOPE = {
  PLATFORM: 'platform',
  ORGANIZATION: 'organization',
  BRANCH: 'branch',
  SELF: 'self',
  CUSTOMER: 'customer',
} as const;

export type RoleScope = (typeof ROLE_SCOPE)[keyof typeof ROLE_SCOPE];

export interface SystemRoleDefinition {
  key: string;
  name: string;
  description: string;
  scope: RoleScope;
  /** Data visibility default; a user may be narrowed further by branch assignment. */
  dataScope: 'all' | 'branch' | 'assigned' | 'self' | 'customer';
  permissions: string[];
  /** System roles are seeded and protected from deletion. */
  system: true;
}

