import { test, expect } from '@playwright/test';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { readFileSync, mkdirSync } from 'node:fs';
import { parseEnv } from 'node:util';
import { randomUUID, randomBytes } from 'node:crypto';
import { state } from './support.mjs';
const env = state();
const req = createRequire(resolve('backend/apps/api/package.json'));
const { PrismaClient } = req('@operix/database');
const { PILOT_ROLES } = req('@operix/permissions');
const argon2 = req('argon2');
const url = new URL(process.env.TEST_DATABASE_URL ?? parseEnv(readFileSync('backend/.env', 'utf8')).DATABASE_URL);
if (!['localhost', '127.0.0.1'].includes(url.hostname) || !/^browser_test_[a-f0-9]{32}$/.test(env.schema)) throw Error('Disposable local schema required');
url.searchParams.set('schema', env.schema);
const db = new PrismaClient({ datasourceUrl: url.toString() });
test.afterAll(() => db.$disconnect());
test.use({ trace: 'off' });
for (const mobile of [false, true]) test(`multi-role real API and UI ${mobile ? 'mobile' : 'desktop'}`, async ({ page, request }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 });
  const run = randomUUID();
  const org = await db.organization.create({ data: { name: 'Global High Tech (GHT) ? SYNTHETIC', slug: `ght-multirole-${run}`, status: 'ACTIVE' } });
  for (const module of await db.module.findMany()) await db.organizationModule.create({ data: { organizationId: org.id, moduleId: module.id } });
  const roles = {};
  for (const r of PILOT_ROLES) roles[r.key] = await db.role.create({ data: { organizationId: org.id, name: r.name, systemKey: r.key, dataScope: r.dataScope, permissions: [...r.permissions] } });
  const foreignOrg = await db.organization.create({ data: { name: 'Other SYNTHETIC tenant', slug: `foreign-${run}`, status: 'ACTIVE' } });
  const foreignRole = await db.role.create({ data: { organizationId: foreignOrg.id, name: 'Foreign administrator', permissions: [...roles.ght_admin.permissions] } });
  const branch = await db.branch.create({ data: { organizationId: org.id, name: 'GHT Test Branch', code: 'TEST', country: 'US', currency: 'USD', timezone: 'America/New_York' } });
  const other = await db.branch.create({ data: { organizationId: org.id, name: 'Restricted Branch', code: 'OTHER', country: 'US', currency: 'USD', timezone: 'America/New_York' } });
  const project = await db.businessRecord.create({ data: { organizationId: org.id, branchId: branch.id, module: 'projects', type: 'project', name: 'Synthetic project', createdBy: randomUUID(), updatedBy: randomUUID() } });
  const password = `Synthetic-${randomBytes(16).toString('hex')}`;
  const makeUser = async (name, key, branches) => {
    const user = await db.user.create({ data: { email: `${name.toLowerCase()}.${run}@browser.test`, firstName: name, lastName: 'Synthetic', passwordHash: await argon2.hash(password) } });
    const member = await db.organizationUser.create({ data: { organizationId: org.id, userId: user.id, roleId: roles[key].id, branchIds: branches } });
    return { user, member };
  };
  const admin = await makeUser('Admin', 'ght_admin', []);
  const employee = await makeUser('Employee', 'ght_sales', [branch.id]);
  const login = async (who) => {
    const res = await request.post(`${env.api}/api/v1/auth/login`, { data: { email: who.user.email, password } });
    expect(res.status()).toBe(201); return res.json();
  };
  const adminSession = await login(admin);
  const call = (session, method, path, data, tenant = org.id) => request.fetch(`${env.api}/api/v1${path}`, { method, headers: { Authorization: `Bearer ${session.accessToken}`, 'x-organization-id': tenant }, data });
  const openSession = async (s, path = '/dashboard') => {
    await page.goto(env.web);
    await page.evaluate((s) => localStorage.setItem('operix.pilot.session', JSON.stringify(s)), s);
    await page.goto(`${env.web}${path}`);
    await expect(page.locator('.px-role-menu')).toBeVisible();
  };
  await openSession(adminSession, '/team');
  await page.getByRole('button', { name: 'Change access for Employee', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Project Manager', { exact: true }).check();
  await dialog.getByLabel('Production', { exact: true }).check();
  mkdirSync('e2e/evidence/multi-role', { recursive: true });
  await page.screenshot({ path: `e2e/evidence/multi-role/${mobile ? 'mobile' : 'desktop'}-assignment.png`, fullPage: true, animations: 'disabled' });
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog).toBeHidden();
  expect(await db.membershipRole.count({ where: { membershipId: employee.member.id } })).toBe(3);
  const deniedOwner = await call(adminSession, 'PATCH', `/organization/users/${employee.member.id}`, { roleIds: [roles.ght_owner.id], branchIds: [branch.id] });
  expect(deniedOwner.status()).toBe(403);
  let s = await login(employee);
  await openSession(s);
  await page.locator('.px-role-menu summary').click();
  const select = page.getByLabel('Active role', { exact: true });
  expect(await select.locator('option').allTextContents()).toEqual(expect.arrayContaining(['Sales Representative', 'Project Manager', 'Production']));
  expect(await select.locator('option').count()).toBe(3);
  await expect(page.getByRole('navigation').getByRole('link', { name: 'Tasks', exact: true })).toHaveCount(0);
  mkdirSync('e2e/evidence/multi-role', { recursive: true });
  await expect(page.locator('.px-role-panel')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `e2e/evidence/multi-role/${mobile ? 'mobile' : 'desktop'}-switcher.png`, fullPage: true, animations: 'disabled' });
  expect((await call(s, 'POST', '/auth/switch-role', { roleId: roles.ght_admin.id })).status()).toBe(403);
  expect((await call(s, 'GET', '/organization/users')).status()).toBe(403);
  expect((await call(s, 'GET', '/organization', undefined, foreignOrg.id)).status()).toBe(403);
  expect((await call(s, 'POST', '/auth/switch-role', { roleId: foreignRole.id })).status()).toBe(403);
  expect((await call(adminSession, 'PATCH', `/organization/users/${employee.member.id}`, { roleIds: [foreignRole.id] })).status()).toBe(400);
  const record = await db.businessRecord.create({ data: { organizationId: org.id, branchId: other.id, module: 'customers', type: 'customer', name: 'Restricted customer', createdBy: employee.user.id, updatedBy: employee.user.id } });
  expect((await call(s, 'GET', `/records/customers/${record.id}`)).status()).toBe(404);
  expect((await call(s, 'POST', '/records', { module: 'customers', type: 'customer', name: 'Forbidden branch customer', status: 'ACTIVE', branchId: other.id, data: {} })).status()).toBe(403);
  await select.selectOption(roles.ght_project_manager.id);
  await expect(select).toHaveValue(roles.ght_project_manager.id);
  if (mobile) await page.getByRole('button', { name: 'Open menu', exact: true }).click();
  await expect(page.getByRole('navigation').getByRole('link', { name: 'Tasks', exact: true })).toBeVisible();
  if (mobile) await page.getByRole('button', { name: 'Close menu', exact: true }).click();
  expect((await call(s, 'POST', '/records', { module: 'tasks', type: 'task', name: 'Allowed task', status: 'PENDING', branchId: branch.id, data: { projectId: project.id } })).status()).toBe(201);
  await page.reload();
  await page.locator('.px-role-menu summary').click();
  await expect(select).toHaveValue(roles.ght_project_manager.id);
  await select.selectOption(roles.ght_production.id);
  await expect(select).toHaveValue(roles.ght_production.id);
  await expect(page.getByRole('navigation').getByRole('link', { name: 'Quotations', exact: true })).toHaveCount(0);
  expect((await call(s, 'GET', '/records/quotations')).status()).toBe(403);
  expect((await call(s, 'GET', `/records/customers/${record.id}`)).status()).toBe(404);
  expect((await call(adminSession, 'PATCH', `/organization/users/${employee.member.id}`, { roleIds: [roles.ght_sales.id], branchIds: [branch.id] })).status()).toBe(200);
  expect((await call(s, 'POST', '/auth/switch-role', { roleId: roles.ght_production.id })).status()).toBe(403);
  expect((await call(s, 'POST', '/records', { module: 'tasks', type: 'task', name: 'Revoked permission', branchId: branch.id, data: {} })).status()).toBe(403);
  await page.reload();
  await page.locator('.px-role-menu summary').click();
  await expect(select).toHaveValue(roles.ght_sales.id);
  s = await login(employee);
  expect(s.role.id).toBe(roles.ght_sales.id);
  expect(await db.auditLog.count({ where: { organizationId: org.id, userId: employee.user.id, action: 'ROLE_SWITCHED' } })).toBe(2);
  const approved = ['ght_sales', 'ght_project_manager', 'ght_production', 'ght_employee', 'ght_finance', 'ght_sales_manager', 'ght_admin'];
  expect((await call(adminSession, 'PATCH', `/organization/users/${employee.member.id}`, { roleIds: approved.map((k) => roles[k].id), branchIds: [branch.id] })).status()).toBe(200);
  for (const key of approved) {
    const result = await call(s, 'POST', '/auth/switch-role', { roleId: roles[key].id });
    expect(result.status()).toBe(201);
    expect((await result.json()).role.id).toBe(roles[key].id);
  }
  await db.organization.update({ where: { id: org.id }, data: { settings: { security: { mfaRequiredRoleKeys: ['ght_finance'] } } } });
  const gated = await call(s, 'POST', '/auth/switch-role', { roleId: roles.ght_finance.id });
  expect(gated.status()).toBe(201); expect((await gated.json()).mfaEnrollmentRequired).toBe(true);
  expect((await call(s, 'GET', '/records/customers')).status()).toBe(403);
  const refresh = await request.post(`${env.api}/api/v1/auth/refresh`, { data: { refreshToken: s.refreshToken } });
  expect(refresh.status()).toBe(201);
  s = { ...s, ...await refresh.json() };
  expect((await (await call(s, 'GET', '/auth/me')).json()).role.id).toBe(roles.ght_finance.id);
  expect((await call(s, 'GET', '/records/customers')).status()).toBe(403);
  await db.session.updateMany({ where: { userId: employee.user.id }, data: { revokedAt: new Date() } });
  expect((await call(s, 'POST', '/auth/switch-role', { roleId: roles.ght_admin.id })).status()).toBe(401);
  expect((await request.post(`${env.api}/api/v1/auth/switch-role`, { data: { roleId: roles.ght_admin.id } })).status()).toBe(401);
});
